export type TranslationKey = keyof typeof translations;

export function getTranslation(
  section: TranslationKey,
  key: string,
  lang: Lang,
): string {
  const sec = translations[section] as TranslationSection | undefined;
  if (!sec) return key;
  const val = sec[key];
  if (!val) return key;
  return val[lang] ?? val["en"] ?? key;
}
